const fs=require('fs'),solc=require('solc'),ganache=require('ganache'),{ethers}=require('ethers'),assert=require('assert/strict');
(async()=>{
 const source=fs.readFileSync('contracts/CampusGearLending.sol','utf8');
 const output=JSON.parse(solc.compile(JSON.stringify({language:'Solidity',sources:{'CampusGearLending.sol':{content:source}},settings:{outputSelection:{'*':{'*':['abi','evm.bytecode']}}}})));
 const artifact=output.contracts['CampusGearLending.sol'].CampusGearLending;
 const provider=new ethers.BrowserProvider(ganache.provider({logging:{quiet:true}}));
 const [owner,alice,bob]=await Promise.all([provider.getSigner(0),provider.getSigner(1),provider.getSigner(2)]);
 console.log('signers ready');
 const ledger=await new ethers.ContractFactory(artifact.abi,artifact.evm.bytecode.object,owner).deploy();await ledger.waitForDeployment();
 console.log('deployed');
 const due=Math.floor(Date.now()/1000)+86400;
 const rejects=async (fn)=>{let rejected=false;try{await fn()}catch(e){rejected=true}assert.ok(rejected,'Expected revert')};
 await rejects(()=>ledger.connect(alice).addItem('Camera'));
 await rejects(()=>ledger.addItem(''));
 await (await ledger.addItem('Camera')).wait();
 await rejects(()=>ledger.connect(alice).requestLoan(99,due));
 await rejects(()=>ledger.connect(alice).requestLoan(1,1));
 await (await ledger.connect(alice).requestLoan(1,due)).wait();
 await rejects(()=>ledger.connect(bob).requestLoan(1,due));
 await rejects(()=>ledger.connect(bob).approveLoan(1));
 await rejects(()=>ledger.connect(bob).cancelRequest(1));
 await (await ledger.approveLoan(1)).wait();
 await rejects(()=>ledger.connect(bob).markReturned(1));
 await (await ledger.connect(alice).markReturned(1)).wait();
 await (await ledger.confirmReturn(1)).wait();
 assert.equal((await ledger.getItem(1)).currentLoanId,0n);
 assert.equal((await ledger.getLoan(1)).status,3n);
 await (await ledger.connect(bob).requestLoan(1,due)).wait();
 await (await ledger.connect(bob).cancelRequest(2)).wait();
 assert.equal((await ledger.getItem(1)).currentLoanId,0n);
 console.log('PASS: local Ganache deployment, full lifecycle, cancellation, invalid and unauthorised calls');
})().catch(e=>{console.error(e);process.exit(1)});
